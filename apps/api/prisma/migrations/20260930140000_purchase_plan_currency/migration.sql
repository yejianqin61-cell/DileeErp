-- 采购计划行的币种（2026-09-30）
--
-- 依据：docs/design/purchase-plan-pricing-2026-09-30.md
-- 用户原话：「针对当前的采购计划，要求添加价格字段，单价，总价。不然财务没法付钱。」
--
-- 为什么币种落在**行**上、不落在计划头上：一张计划里同时有多个供应商（口径 1），
-- 而"一个币种"是**一张采购单**的属性（采购单粒度 = 一个供应商 × 一个币种）。
-- 币种固定在计划头上，等于把"不同供应商可能报不同货币"从数据模型里删掉，
-- 计划合计也就只能跨币种相加 —— 而仓库的既有约定是「金额不跨币种合计」。
--
-- 为什么是 NOT NULL DEFAULT 'CNY'：
--   · 历史行与新建行都必须有一个可显示、可合计的币种；可空会让合计多出"币种未知"一档，
--     而界面上没有任何地方能把它补回来（币种是在「收束下单」时按供应商组选的，
--     见 purchase-plans.service.ts 的 order()：按组币种写回这一组每一行）。
--   · 常量默认值：PostgreSQL 11+ 加这种列不重写全表，历史行读到的是同一个默认值。
--
-- 不加索引：这一列只跟着行一起读，从不作为查询条件。

ALTER TABLE "purchase_plan_items"
  ADD COLUMN "currency" VARCHAR(10) NOT NULL DEFAULT 'CNY';
