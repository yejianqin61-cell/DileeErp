-- BOM 明细行加「参考单价 + 币种」（2026-10-08）
--
-- 依据：用户原话「采购计划要下单需要填写单价，但是BOM表没办法填写单价，检查一下这条链路。尤其是前端。」
-- 排查结论（见 docs/design/bom-reference-unit-price-2026-10-08.md）：
--   · 前端的单价输入框**本来是有的**（采购计划 → 打开计划 → 明细表第 8 列），保存与下单都正常；
--     真正缺的是"价格从哪来" —— 从 BOM 新建的计划行单价写死 0，采购员只能凭记忆逐行打。
--   · 用户选定：在 BOM 行上手填参考单价（含币种），新建采购计划时**预填**到计划行，仍可改。
--
-- 三条取舍（与「默认供应商」那条迁移同形）：
--   · **两列都可空**：历史 BOM 行没有价；`NULL` = 没填，与「填了 0」不是一件事
--     （0 价不能下单，所以 0 等价于没填，但库里仍如实存着用户填过的值）。
--   · **不参与任何金额计算**：成本/毛利/应付一律取采购单上的实际单价
--     （`finance-report-cost.service.ts` 的取价口径没变）；这里只是"这个部件通常多少钱"。
--   · **币种按行记**：不记币种的话，美元报价预填到计划里会让"计划合计按币种分列"说谎。
--
-- 这条迁移是**纯加列**（无默认值、无 NOT NULL、无外键、无索引）：PostgreSQL 只改目录，
-- 不重写表；历史行两列都是 NULL。没有数据改写，因此也没有需要拦的守卫。
-- 部署顺序仍是先 `prisma migrate deploy`，再发代码（前后端一起）：新前端保存 BOM 时会带上这两列，
-- 列不存在会直接报错。

ALTER TABLE "bom_items"
  ADD COLUMN "reference_unit_price" DECIMAL(18,4),
  ADD COLUMN "reference_currency" VARCHAR(10);
