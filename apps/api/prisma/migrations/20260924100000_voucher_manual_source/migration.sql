-- 手工凭证的来源可以为空（2026-09-24）
--
-- 财务要录**非现金分录**（折旧、摊销、工资计提、结转成本），它们没有来源单据 ——
-- 而凭证原先只能由收支流水生成（`source_id` 是 NOT NULL），于是这些分录在系统里根本没有落点，
-- 三大报表的「固定资产 / 累计折旧 / 应付职工薪酬」等行永远填不上。
--
-- 为什么加「可空」而不是「填一个随机 UUID」：`source_id` 是一个**引用**（列表页靠它去取
-- 来源流水号、红冲凭证靠它指向被红冲的那张）。填一个编造的 id 会让这一列在语义上说谎，
-- 以后任何按来源追溯的地方都要额外判断「这个 id 是不是真的」。
--
-- 唯一索引 `vouchers_source_type_source_id_key` **不动**：PostgreSQL 的唯一索引不约束 NULL，
-- 因此多张手工凭证 (manual, NULL) 可以共存，而「一条来源只能有一张凭证」（生成接口的幂等根）
-- 对收支流水来源依然成立。
ALTER TABLE "vouchers" ALTER COLUMN "source_id" DROP NOT NULL;
