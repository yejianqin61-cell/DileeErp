-- 销售单「材料明细」同类目再加一款（用户 2026-10-29：
-- 「材料明细那边可以在现有基础上自行添加类目。比如我这一单有3款伞头，2款伞布。
--   就支持自行添加类目来填写。同时，销售单的导出件也要同步跟上」）。
--
-- 为什么加列而不是新表：一行仍然是一条「类目 + 内容 + 物料引用」，与新表相比只多了一个
-- 「它属于 18 个固定类目里的哪一个」的归属键。另建一张表要把「谁先印」这条排版顺序拆到两处
-- （固定类目在导出服务的常量里、新增行在新表里），而导出顺序是这个功能的**全部意义**。
--
-- 为什么可空：原有「其它」行还是自由类目（用户自己起名），它们没有归属。
--   NULL = 原有行为（印在 18 项之后），非 NULL = 印在该类目那一行之后。
--
-- 为什么叫 spec_key：同一个词已经在 `sales_order_material_refs.spec_key` 上用着，
--   语义完全一样（18 个材料栏位之一的键），换名字只会让人以为两者不是一回事。
--
-- 没有唯一键：本表的替换语义是「软删旧的 + 建新的」（与 `sales_order_spec_details` 一致），
--   同一个类目可以有多行（这正是「3 款伞头」）。
ALTER TABLE "sales_order_material_extras" ADD COLUMN "spec_key" VARCHAR(40);
